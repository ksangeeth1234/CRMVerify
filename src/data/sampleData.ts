/**
 * Creates and downloads a real Excel .xlsx file for Master Student Database
 */
export function generateSampleMasterExcelFile(): void {
  // Strip _rowIndex before generating
  const cleanData = SAMPLE_MASTER_STUDENTS.map(({ _rowIndex, ...rest }) => rest);
  const worksheet = XLSX.utils.json_to_sheet(cleanData);
  const workbook = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(workbook, worksheet, 'Students Master');

  // Also add a secondary sheet to test multi-sheet workbook support!
  const metaSheet = XLSX.utils.json_to_sheet([
    { 'Property': 'Institution', 'Value': 'National University College' },
    { 'Property': 'Academic Year', 'Value': '2024/2025' },
    { 'Property': 'Generated Date', 'Value': '2024-10-22' },
    { 'Property': 'Total Records', 'Value': cleanData.length },
  ]);
  XLSX.utils.book_append_sheet(workbook, metaSheet, 'Metadata & Notes');

  XLSX.writeFile(workbook, 'Master_Student_Database_Sample.xlsx');
}

